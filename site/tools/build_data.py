"""Build site/assets/data.js from the repository's own result files (nothing typed by hand).

Sources: report/figures/data/{sim_delay,sim_delay_summary,example_patient}.dat (exported from the OMNeT++ run r6 and the
deployed model), simulation/omnetpp/imported_results/circular-mixed-route-r6.json, ml/models/ew-20261114/metrics.json.
Run from the repository root:  python site/tools/build_data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "report" / "figures" / "data"


def table(path):
    lines = [l.split() for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]
    head = lines[0]
    rows = []
    for l in lines[1:]:
        rows.append({k: (None if v == "nan" else float(v)) for k, v in zip(head, l)})
    return rows


sim = json.loads((ROOT / "simulation" / "omnetpp" / "imported_results" / "circular-mixed-route-r6.json").read_text(encoding="utf-8"))
packets = [{"t": round(r["t"], 6), "delay_ms": r["delay_ms"], "hop": int(r["hop"]), "patient": int(r["patient"])} for r in table(DATA / "sim_delay.dat")]
assert len(packets) == sim["doctor_valid"] == 79
summary = [{"hop": int(r["hop"]), "n": int(r["n"]), "sim_ms": r["sim_ms"], "analytic34_ms": r["analytic34_ms"]} for r in table(DATA / "sim_delay_summary.dat")]
metrics = json.loads((ROOT / "ml" / "models" / "ew-20261114" / "metrics.json").read_text(encoding="utf-8"))
models = []
for name, m in metrics["models"].items():
    t = m["test"]
    models.append({"name": name, "deployable": m.get("deployable", False), "pr_auc": round(t["pr_auc"], 3), "roc_auc": round(t["roc_auc"], 3),
                   "precision": round(t["precision"], 3), "recall": round(t["recall"], 3), "f1": round(t["f1"], 3),
                   "episodes": f'{t["events"]["detected"]}/{t["events"]["events"]}', "fa_per_day": round(t["events"]["false_alarms_per_patient_day"], 2),
                   "latency_ms": m.get("inference_latency_ms")})
sel = metrics["models"][metrics["selected"]]["test"]
traj = [{"t": round(r["tmin"], 3), "hr": r["hr"], "spo2": r["spo2"], "score": None if r["score"] is None else round(r["score"], 4)}
        for r in table(DATA / "example_patient.dat") if -40 <= r["tmin"] <= 15]
out = {
    "source": {"omnet_run": sim["source"], "model": metrics["version"], "generated_from": "site/tools/build_data.py"},
    "sim": {k: sim[k] for k in ("patients", "relays", "generated", "doctor_valid", "direct", "relay_assisted", "pdr", "duplicates", "sim_time")},
    "relay_stats": sim["relay_stats"],
    "lost": {"patient": 18, "seq": 1, "at_relay": 1, "rx_dbm": -124.8, "note": "received below SF7/125 kHz sensitivity (-124 dBm)"},
    "packets": packets,
    "delay_summary": summary,
    "airtime_ms": {"v2_34B": 77.1, "json_241B": 379.1},
    "model": {"selected": metrics["selected"], "precision": round(sel["precision"], 3), "recall": round(sel["recall"], 3), "specificity": round(sel["specificity"], 3),
              "pr_auc": round(sel["pr_auc"], 3), "roc_auc": round(sel["roc_auc"], 3), "prevalence": round(sel["prevalence"], 4),
              "episodes": sel["events"], "thresholds": {"high": 0.645, "medium": 0.231}, "models": models},
    "trajectory": traj,
    "dataset": {"profiles": 600, "samples": 627099, "episodes": {"HR rise": 157, "SpO2 decline": 152, "benign HR rise": 138, "combined": 102,
                                                                  "fever": 94, "benign SpO2 dip": 71, "abrupt change": 44, "fall": 29}},
    "tests": {"passed": 233, "total": 233, "date": "2026-11-21"},
}
dest = ROOT / "site" / "assets" / "data.js"
dest.write_text("/* generated by site/tools/build_data.py from the repository's result files - do not edit */\nwindow.RPM_DATA = "
                + json.dumps(out, separators=(",", ":")) + ";\n", encoding="utf-8")
print("wrote", dest.relative_to(ROOT), dest.stat().st_size, "bytes;", len(packets), "packets,", len(traj), "trajectory points")
